"""UI operations independent of widgets, wire method names and parameter types."""
from concurrent.futures import Future
from typing import Callable, Literal, Protocol

Preference = Literal['tent_enabled', 'tent_prompt', 'stand_prompt', 'suspend_touch_wake']
PREFERENCES = frozenset({'tent_enabled', 'tent_prompt', 'stand_prompt', 'suspend_touch_wake'})


class UIClient(Protocol):
    """Consume validated snapshots; complete futures on the UI's owner loop.

    Platform adapters marshal all callbacks to that loop, bound their I/O and
    invalidate outstanding requests on disconnect. A successful operation is
    an accepted request, not evidence that a target has been applied.
    """

    def start(self, on_state: Callable[[dict], None],
              on_unavailable: Callable[[], None],
              on_connected: Callable[[], None] | None = None) -> None: ...
    def stop(self) -> None: ...
    def refresh(self) -> None: ...
    def set_mode(self, mode: str) -> Future: ...
    def set_preference(self, field: Preference, enabled: bool) -> Future: ...
    def confirm_prompt(self, prompt: str | None, epoch: int) -> Future: ...
    def calibrate(self) -> Future: ...
    def reset_calibration(self) -> Future: ...
    def retry(self, fallback_mode: str | None = None) -> Future: ...
